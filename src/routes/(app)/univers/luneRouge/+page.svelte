	<h1 id="le-culte-de-la-lune-rouge">Le Culte de la Lune Rouge</h1>
	<p>
		Voici les différents manuscrits qui parlent de la Lune Rouge. Ces récits servent à expliquer et
		comprendre les prophéties données au fil des siècles par les cultistes de la Lune Rouge. Ces
		manuscrits ne sont, ni de l&#39;histoire, ni de la fiction, ni un recueil, ils sont tout ça à la
		fois. Ils n&#39;ont de figure d&#39;autorités que dans la conscience morale qui habite leures
		lectrices.
	</p>
	<h2 id="les-trois-voies">Les trois voies</h2>
	<p>
		Les Prophéties du culte peuvent être lues de différentes manières. Trois interprétations, et
		donc courant de pensées, dominent. On les nommes les &quot;Voies&quot;.
	</p>
	<p>
		La première Voie fût celle de Azal Araki, première prophétesse et scribe de la Lune Rouge. Elle
		a une interprétation matérialiste et fédératrice des textes et souhaite intégrer le monde entier
		au culte. Pour cette mission, elle a fondée et dirige l&#39;Aube Écarlate.
	</p>
	<p>
		La Deuxième Voie est celle de Jost, le colonel. Il a produit une interprétation guerrière et
		élitiste des prophéties. Pour lui, seules les plus méritantes devraient entrer dans le culte.
	</p>
	<p>
		Enfin, plus marginale, mais qui a récemment pris de l&#39;importance, Mamie Glycine, qui apporte
		une lecture plus libéral des Prophéties. Les fidèles ne suivent pas forcément une seule voie.
	</p>
